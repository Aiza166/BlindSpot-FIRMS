"""Render docs/RESULTS_T1.md from data/processed/results/t1.json. No number is typed here:
every figure in the Markdown is read from the JSON (CLAUDE.md rule 7).

    python -m blindspot.report_t1 --json data/processed/results/t1.json --md docs/RESULTS_T1.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

MONTHS = {10: "Oct", 11: "Nov"}
LABEL = {"PK_Punjab": "PK Punjab", "IN_Punjab": "IN Punjab", "rest_of_box": "Rest of box"}


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:+.1f}%"


def _f(x: float | None, nd: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}"


def _n(x: float) -> str:
    return f"{x:,.0f}"


def _yes(b: bool) -> str:
    return "pass" if b else "fail"


def render(t1: dict, t2: dict | None = None) -> str:
    prm = t1["parameters"]
    cy, hy = prm["calib_years"], prm["heldout_years"]
    prov = t1["provenance"]
    out = [
        "# T1 harmonization results",
        "",
        f"Generated by `python -m blindspot.report_t1` from `data/processed/results/t1.json` "
        f"({t1['generated']}). Do not edit by hand. Definitions: `docs/DECISIONS.md` D-028; "
        "test as pre-registered in `docs/PLAN.md` §4.",
        "",
        f"- Regions: {', '.join(LABEL.get(r, r) for r in t1['regions'])} (geoBoundaries ADM1), "
        "each alone.",
        f"- Window: {t1['window']['start']} to {t1['window']['end']} by "
        f"{t1['window']['time_basis']}; common available Aqua/S-NPP days only.",
        f"- Calibration years {cy[0]}–{cy[-1]}; held-out {hy[0]}–{hy[-1]}; "
        f"bootstrap B = {prm['bootstrap_b']}, seed {prm['seed']}.",
        f"- Code commit `{prov['code']['commit']}`"
        + (" (pipeline code had uncommitted changes)" if prov["code"]["code_dirty"] else "")
        + ".",
        "",
        "## Verdict (primary unit: hotspot counts)",
        "",
        "| Region | 2012 step | Held-out | T1 | Status |",
        "|---|---|---|---|---|",
    ]
    for r, v in t1["verdict_primary"].items():
        out.append(
            f"| {LABEL.get(r, r)} | {_yes(v['step_pass'])} | {_yes(v['heldout_pass'])} | "
            f"{_yes(v['pass'])} | {v['status']} |"
        )
    out += ["", f"_{next(iter(t1['verdict_primary'].values()))['note']}_", ""]
    if t2 is not None:
        out += ["## Final T1 after T2 (D-034)", "", "| Region | T2 revised | T1 |", "|---|---|---|"]
        for r, v in t2["t1_reevaluated"].items():
            out.append(
                f"| {LABEL.get(r, r)} | {t2['verdict_t2_revised'][r]['label']} | {v['label']} |"
            )
        out.append("")

    prim = t1["results"][t1["primary_unit"]]
    out += [
        "## (a) 2012 step",
        "",
        f"Raw step = S-NPP / Aqua − 1 in the {prm['step_year']} window. Harmonized step = "
        f"S-NPP / (Aqua × factor) − 1 with factors fit on {prm['step_fit_years'][0]}–"
        f"{prm['step_fit_years'][-1]} only. Pass if |harmonized| / |raw| < "
        f"{prm['step_threshold']:.2f}.",
        "",
        "| Region | Aqua | S-NPP | Aqua-predicted | Raw step | Harmonized step | Ratio | "
        "Ratio 95% interval | Result |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r, res in prim.items():
        s = res["step_2012"]
        out.append(
            f"| {LABEL.get(r, r)} | {_n(s['aqua_window_total'])} | {_n(s['snpp_window_total'])} | "
            f"{_n(s['aqua_predicted_total'])} | {_pct(s['raw_step'])} | "
            f"{_pct(s['harmonized_step'])} | {_f(s['ratio'])} | "
            f"{_f(s['ratio_ci95'][0])}–{_f(s['ratio_ci95'][1])} | {_yes(s['pass'])} |"
        )
    out += [
        "",
        "## (b) Held-out years",
        "",
        "Observed S-NPP window total vs Aqua × factor (factors fit on all calibration years). "
        "The 95% prediction interval comes from leave-one-year-out log residuals over the "
        "calibration years.",
        "",
    ]
    for r, res in prim.items():
        h = res["heldout"]
        out += [
            f"**{LABEL.get(r, r)}**: residual mean {_f(h['residual_mean'])}, sd "
            f"{_f(h['residual_sd'])}, interval (log) {_f(h['pi_log'][0])} to "
            f"{_f(h['pi_log'][1])}; {h['n_inside']} of {h['n']} years inside → "
            f"{_yes(h['pass'])}.",
            "",
            "| Year | Aqua | Aqua-predicted | Observed S-NPP | 95% prediction interval | Inside |",
            "|---|---|---|---|---|---|",
        ]
        for y in h["years"]:
            lo, hi = y["observed_pi95"]
            out.append(
                f"| {y['year']} | {_n(y['aqua_window_total'])} | {_n(y['aqua_predicted'])} | "
                f"{_n(y['observed'])} | {_n(lo)}–{_n(hi)} | {'yes' if y['inside'] else 'no'} |"
            )
        out.append("")

    out += [
        "## Calibration factors, Oct and Nov (Aqua → S-NPP, hotspot counts)",
        "",
        "| Region | Month | Factor | 95% interval | Years |",
        "|---|---|---|---|---|",
    ]
    for f in t1["calibration_factors"]:
        if f["pair"] == "Aqua->SNPP" and f["unit"] == t1["primary_unit"] and f["month"] in MONTHS:
            out.append(
                f"| {LABEL.get(f['region'], f['region'])} | {MONTHS[f['month']]} | "
                f"{_f(f['factor'])} | {_f(f['lo'])}–{_f(f['hi'])} | {f['n_years']} |"
            )
    out += [
        "",
        "## Robustness: fire cell-days (not a verdict)",
        "",
        "| Unit | Region | Oct factor | Nov factor | Step ratio | Held-out inside |",
        "|---|---|---|---|---|---|",
    ]
    for unit, by_region in t1["results"].items():
        for r, res in by_region.items():
            s, h = res["step_2012"], res["heldout"]
            fac = {
                f["month"]: f["factor"]
                for f in t1["calibration_factors"]
                if f["pair"] == "Aqua->SNPP" and f["unit"] == unit and f["region"] == r
            }
            out.append(
                f"| {unit} | {LABEL.get(r, r)} | {_f(fac.get(10))} | {_f(fac.get(11))} | "
                f"{_f(s['ratio'])} | {h['n_inside']}/{h['n']} |"
            )
    out += [
        "",
        "## Saturated cells (both Aqua and S-NPP active / either active), 2012–2021",
        "",
        "| Region | Grid | Oct | Nov |",
        "|---|---|---|---|",
    ]
    sat: dict[tuple[str, float], dict[int, float]] = {}
    for s in t1["saturation_2012_2021_by_month"]:
        sat.setdefault((s["region"], s["grid_deg"]), {})[s["month"]] = s["share_saturated"]
    for (r, g), by_m in sorted(sat.items()):
        if r in t1["regions"]:
            out.append(
                f"| {LABEL.get(r, r)} | {g:g}° | {_pct(by_m.get(10))[1:]} | "
                f"{_pct(by_m.get(11))[1:]} |"
            )
    out += ["", "## Inputs", "", "| Input | sha256 | Files |", "|---|---|---|"]
    for k, v in prov["inputs"].items():
        out.append(f"| {k} | `{(v.get('sha256') or 'missing')[:16]}` | {v.get('n_files', 0)} |")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--json", type=Path, default=Path("data/processed/results/t1.json"))
    p.add_argument("--md", type=Path, default=Path("docs/RESULTS_T1.md"))
    p.add_argument("--t2", type=Path, default=None, help="t2.json for the final T1 label")
    args = p.parse_args(argv)
    t2 = json.loads(args.t2.read_text()) if args.t2 and args.t2.exists() else None
    args.md.write_text(render(json.loads(args.json.read_text()), t2))
    print(f"-> {args.md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
