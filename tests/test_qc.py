"""Tests for blindspot.qc. All inputs are hand-written fixtures (see conftest.py)."""

from __future__ import annotations

import json
import shutil

import pytest

from blindspot import ingest, mask, qc


@pytest.fixture
def two_copies(tmp_path, fixtures_dir):
    """MODIS fixture twice (to create duplicates) + the S-NPP fixture."""
    raw = tmp_path / "raw"
    raw.mkdir()
    shutil.copy(fixtures_dir / "fixture_modis_country.csv", raw / "a_modis.csv")
    shutil.copy(fixtures_dir / "fixture_modis_country.csv", raw / "b_modis.csv")
    shutil.copy(fixtures_dir / "fixture_viirs_snpp_country.csv", raw / "viirs-snpp.csv")
    out = tmp_path / "hotspots"
    log = ingest.ingest_dir(raw, out)
    return ingest.connect(out), log


def _row(report, platform, year):
    return next(r for r in report["counts"] if r["platform"] == platform and r["year"] == year)


def test_stage_counts_are_sequential(two_copies):
    con, log = two_copies
    rep = qc.build_report(con, log)
    assert _row(rep, "Aqua", 2015) == {
        "platform": "Aqua",
        "year": 2015,
        "raw": 6,
        "after_standard": 6,
        "after_type": 6,
        "after_confidence": 6,
        "after_box": 4,
        "after_dedup": 2,
        "after_mask": None,
    }
    terra = _row(rep, "Terra", 2015)
    assert (terra["raw"], terra["after_type"], terra["after_confidence"]) == (4, 2, 0)
    snpp = _row(rep, "SNPP", 2016)
    assert (snpp["raw"], snpp["after_type"], snpp["after_confidence"], snpp["after_dedup"]) == (
        4,
        3,
        2,
        2,
    )


def test_mask_stage_counted_when_mask_applied(two_copies):
    con, log = two_copies
    result = mask.build_mask(
        con, grid_deg=0.01, min_years=1, months=(11,), rule="seasonal-offseason"
    )
    mask.apply_mask(con, result)
    rep = qc.build_report(con, log)
    # Every filtered Aqua detection is in November and so in a "persistent" cell here.
    assert _row(rep, "Aqua", 2015)["after_mask"] == 0
    assert _row(rep, "SNPP", 2016)["after_mask"] == 2  # S-NPP rows are in October


def test_duplicates_counted(two_copies):
    con, log = two_copies
    rep = qc.build_report(con, log)
    dups = {(d["platform"], d["year"]): d["n_duplicates"] for d in rep["duplicates"]}
    assert dups == {("Aqua", 2015): 3, ("Terra", 2015): 2, ("SNPP", 2016): 0}


def test_coverage_gaps(tmp_path):
    header = (
        "latitude,longitude,brightness,scan,track,acq_date,acq_time,satellite,instrument,"
        "confidence,version,bright_t31,frp,daynight,type\n"
    )
    body = "".join(
        f"31.5,74.3,330,1,1,{d},0830,A,MODIS,85,6.1,300,25,D,0\n"
        for d in ("2015-01-01", "2015-01-04", "2016-01-02")
    )
    raw = tmp_path / "raw"
    raw.mkdir()
    (raw / "fixture_gaps.csv").write_text(header + body)
    out = tmp_path / "hotspots"
    log = ingest.ingest_dir(raw, out)
    rep = qc.build_report(ingest.connect(out), log)
    gaps = {(g["platform"], g["year"]): g for g in rep["coverage_gaps"]}
    g15 = gaps[("Aqua", 2015)]
    assert (g15["expected_days"], g15["days_with_data"], g15["zero_days"]) == (365, 2, 363)
    assert g15["zero_day_ranges"] == [
        ["2015-01-02", "2015-01-03"],
        ["2015-01-05", "2015-12-31"],
    ]
    g16 = gaps[("Aqua", 2016)]
    assert (g16["expected_days"], g16["zero_days"]) == (2, 1)
    assert g16["zero_day_ranges"] == [["2016-01-01", "2016-01-01"]]


def test_schema_drift(tmp_path, fixtures_dir):
    raw = tmp_path / "raw"
    raw.mkdir()
    shutil.copy(fixtures_dir / "fixture_viirs_snpp_country.csv", raw)
    shutil.copy(fixtures_dir / "fixture_viirs_noaa20_nrt.csv", raw)
    shutil.copy(fixtures_dir / "fixture_modis_country.csv", raw)
    out = tmp_path / "hotspots"
    log = ingest.ingest_dir(raw, out)
    drift = qc.schema_drift(log)
    assert drift["files_with_missing_columns"] == {"fixture_viirs_noaa20_nrt.csv": ["type"]}
    assert drift["files_with_extra_columns"] == {}
    assert drift["drift_detected"] == {"MODIS": False, "VIIRS": True}


def test_write_outputs(two_copies, tmp_path):
    con, log = two_copies
    rep = qc.build_report(con, log)
    jpath, mpath = qc.write_outputs(rep, tmp_path / "qc.json", tmp_path / "QC.md")
    assert json.loads(jpath.read_text())["counts"]
    md = mpath.read_text()
    assert "| Aqua | 2015 |" in md
    assert "Generated by `python -m blindspot.qc`" in md
